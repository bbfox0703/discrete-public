    /// <summary>Sentinel C + 32-byte SHA256 placeholder.</summary>
    private static readonly byte[] HashSlot =
    [
        0x52, 0xE7, 0xB9, 0x0D, 0xC4, 0x71, 0x36, 0xAF,
