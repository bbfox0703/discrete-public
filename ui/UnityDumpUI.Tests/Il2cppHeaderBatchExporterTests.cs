    // ---- end-to-end render ---------------------------------------------------

    [Fact]
    public async Task ExportAsync_EmitsAssemblyBannerAndFqnStructName()
    {
        var asm = new[] { "Assembly-CSharp" };
        var classes = new GetClassesResult
        {
            Assembly = "Assembly-CSharp",
            Count    = 1,
            Classes  = new List<ClassEntry>
            {
                new() { Namespace = "Game", Name = "Player" },
            },
        };
        var classInfo = new GetClassInfoResult
        {
            Namespace = "Game", Name = "Player",
            Parent    = new ClassRef { Namespace = "UnityEngine", Name = "MonoBehaviour" },
            Fields    = new List<FieldEntry>
            {
                new() { Name = "HP",     Type = "System.Int32",  Offset = 0x10, Static = false },
                new() { Name = "MAX_HP", Type = "System.Int32",  Offset = 0x14, Static = false },
                new() { Name = "name",   Type = "System.String", Offset = 0x18, Static = false },
                // Static field — should be skipped from the struct body.
                new() { Name = "Instance", Type = "Game.Player", Offset = 0x00, Static = true  },
            },
            Methods = new List<MethodEntry>
            {
                new() { Name = ".ctor",       Token = 0x06000001, Static = false, Address = "0x00007FF600001000" },
                new() { Name = "TakeDamage",  Token = 0x06000002, Static = false, Address = "0x00007FF600001100" },
                // Mono-style: Address null → not in the address trailer.
                new() { Name = "ResetCache",  Token = 0x06000003, Static = true,  Address = null },
            },
        };

        (string text, Il2cppHeaderBatchExporter.BatchStats stats) =
            await Il2cppHeaderBatchExporter.ExportAsync(
                asm,
                getClasses:   (_, _)        => Task.FromResult(classes),
                getClassInfo: (_, _, _, _)  => Task.FromResult<GetClassInfoResult?>(classInfo),
                ct: TestContext.Current.CancellationToken)
            .ConfigureAwait(true);

        // File header
        Assert.Contains("auto-generated by Discrete", text);
        Assert.Contains("#pragma once", text);
        Assert.Contains("#include <cstdint>", text);

        // Assembly banner
        Assert.Contains("// Assembly: Assembly-CSharp", text);

        // Class banner + inheritance + FQN-based struct name
        Assert.Contains("// Class: Game.Player", text);
        Assert.Contains("// inherits UnityEngine.MonoBehaviour", text);
        Assert.Contains("struct Game_Player {", text);
        Assert.Contains("#pragma pack(push, 1)", text);
        Assert.Contains("#pragma pack(pop)", text);

        // Instance fields with offset comments — static field is excluded.
        Assert.Contains("HP;", text);
        Assert.Contains("// +0x10", text);
        Assert.Contains("MAX_HP;", text);
        Assert.Contains("// +0x14", text);
        Assert.Contains("name;", text);
        Assert.Contains("// +0x18", text);
        Assert.DoesNotContain("Instance;", text);  // static skipped

        // Method address trailer — IL2CPP rows only.
        Assert.Contains("// Methods (AOT entry points", text);
        Assert.Contains(".ctor    @ 0x00007FF600001000", text);
        Assert.Contains("TakeDamage    @ 0x00007FF600001100", text);
        Assert.DoesNotContain("ResetCache", text);  // Address null → not emitted

        // Stats round-trip
        Assert.Equal(1, stats.AssembliesScanned);
        Assert.Equal(1, stats.ClassesEmitted);
        Assert.Equal(0, stats.ClassesFailed);
        Assert.Equal(3, stats.FieldsEmitted);
        Assert.Equal(2, stats.MethodsEmitted);
    }

    [Fact]
    public async Task ExportAsync_SoftFailsClassesWhereGetClassInfoReturnsNull()
    {
        var asm = new[] { "Assembly-CSharp" };
        var classes = new GetClassesResult
        {
            Assembly = "Assembly-CSharp",
            Count    = 2,
            Classes  = new List<ClassEntry>
            {
                new() { Namespace = "Game", Name = "Good" },
                new() { Namespace = "Game", Name = "Broken" },
            },
        };
        GetClassInfoResult goodInfo = new()
        {
            Namespace = "Game", Name = "Good",
            Fields = new List<FieldEntry>
            {
                new() { Name = "x", Type = "System.Int32", Offset = 0x10, Static = false },
            },
        };

        (string text, Il2cppHeaderBatchExporter.BatchStats stats) =
            await Il2cppHeaderBatchExporter.ExportAsync(
                asm,
                getClasses:   (_, _) => Task.FromResult(classes),
                getClassInfo: (_, _, name, _) =>
                    Task.FromResult<GetClassInfoResult?>(name == "Good" ? goodInfo : null),
                ct: TestContext.Current.CancellationToken)
            .ConfigureAwait(true);

        // Good class emitted normally
        Assert.Contains("struct Game_Good {", text);
        // Broken class surfaced as a SKIPPED marker — the file stays
        // a valid concatenation, just with a comment marking the gap.
        Assert.Contains("// SKIPPED Game.Broken — getClassInfo failed", text);
        Assert.DoesNotContain("struct Game_Broken {", text);

        Assert.Equal(1, stats.ClassesEmitted);
        Assert.Equal(1, stats.ClassesFailed);
    }

