    [Fact]
    public void RenderFromBulk_RendersSamePayloadShapeAsLegacyExportAsync()
    {
        var assemblyNames = new[] { "Assembly-CSharp" };
        var bulk = new DumpClassInfoResult
        {
            Count   = 1,
            Scanned = 1,
            Rows    = new List<DumpedClassRow>
            {
                new()
                {
                    Assembly  = "Assembly-CSharp",
                    Namespace = "Game",
                    Name      = "Player",
                    Parent    = new ClassRef { Namespace = "UnityEngine", Name = "MonoBehaviour" },
                    Fields    = new List<FieldEntry>
                    {
                        new() { Name = "HP",     Type = "System.Int32",  Offset = 0x10, Static = false },
                        new() { Name = "MAX_HP", Type = "System.Int32",  Offset = 0x14, Static = false },
                        new() { Name = "name",   Type = "System.String", Offset = 0x18, Static = false },
                        new() { Name = "Instance", Type = "Game.Player", Offset = 0x00, Static = true  },
                    },
                    Methods = new List<MethodEntry>
                    {
                        new() { Name = ".ctor",      Token = 0x06000001, Static = false, Address = "0x00007FF600001000" },
                        new() { Name = "TakeDamage", Token = 0x06000002, Static = false, Address = "0x00007FF600001100" },
                    },
                },
            },
        };

        (string text, Il2cppHeaderBatchExporter.BatchStats stats) =
            Il2cppHeaderBatchExporter.RenderFromBulk(assemblyNames, bulk);

        // Same shape the legacy ExportAsync path produces (already locked
        // in the test above). RenderFromBulk's job is to emit identical
        // output from the bulk RPC payload — anything different is a bug.
        Assert.Contains("auto-generated by Discrete", text);
        Assert.Contains("// Assembly: Assembly-CSharp", text);
        Assert.Contains("// Class: Game.Player", text);
        Assert.Contains("// inherits UnityEngine.MonoBehaviour", text);
        Assert.Contains("struct Game_Player {", text);
        Assert.Contains("HP;",     text); Assert.Contains("// +0x10", text);
        Assert.Contains("MAX_HP;", text); Assert.Contains("// +0x14", text);
        Assert.DoesNotContain("Instance;", text);  // static skipped
        Assert.Contains(".ctor    @ 0x00007FF600001000",       text);
        Assert.Contains("TakeDamage    @ 0x00007FF600001100",  text);

        Assert.Equal(1, stats.AssembliesScanned);
        Assert.Equal(1, stats.ClassesEmitted);
        Assert.Equal(0, stats.ClassesFailed);
        Assert.Equal(3, stats.FieldsEmitted);
        Assert.Equal(2, stats.MethodsEmitted);
    }

    [Fact]
    public void RenderFromBulk_SurfacesPerRowErrorAsSkippedMarker()
    {
        // Server-side ReadClassInfo failures come back as a row with
        // a populated Error string. The renderer must produce the
        // exact same // SKIPPED marker shape that the per-class
        // ExportAsync path emits for null getClassInfo results, so
        // downstream consumers / docs stay consistent.
        var bulk = new DumpClassInfoResult
        {
            Count   = 2,
            Scanned = 2,
            Rows    = new List<DumpedClassRow>
            {
                new()
                {
                    Assembly  = "Assembly-CSharp",
                    Namespace = "Game",
                    Name      = "Good",
                    Fields    = new List<FieldEntry>
                    {
                        new() { Name = "x", Type = "System.Int32", Offset = 0x10, Static = false },
                    },
                    Methods   = new List<MethodEntry>(),
                },
                new()
                {
                    Assembly  = "Assembly-CSharp",
                    Namespace = "Game",
                    Name      = "Broken",
                    Error     = "ReadClassInfo failed",
                },
            },
        };

        (string text, Il2cppHeaderBatchExporter.BatchStats stats) =
            Il2cppHeaderBatchExporter.RenderFromBulk(new[] { "Assembly-CSharp" }, bulk);

        Assert.Contains("struct Game_Good {", text);
        Assert.Contains("// SKIPPED Game.Broken — ReadClassInfo failed", text);
        Assert.DoesNotContain("struct Game_Broken {", text);

        Assert.Equal(1, stats.ClassesEmitted);
        Assert.Equal(1, stats.ClassesFailed);
    }

    [Fact]
    public void RenderFromBulk_PreservesCallerAssemblyOrderForBanners()
    {
        // Server may return rows in any order; renderer must respect
        // the caller's assemblyNames order for the banner layout.
        var assemblyNames = new[] { "Assembly-CSharp-firstpass", "Assembly-CSharp" };
        var bulk = new DumpClassInfoResult
        {
            Count   = 2,
            Rows    = new List<DumpedClassRow>
            {
                // Note rows are in REVERSE assembly order on purpose.
                new() { Assembly = "Assembly-CSharp",          Name = "Late",  Methods = new(), Fields = new() },
                new() { Assembly = "Assembly-CSharp-firstpass", Name = "Early", Methods = new(), Fields = new() },
            },
        };

        (string text, _) =
            Il2cppHeaderBatchExporter.RenderFromBulk(assemblyNames, bulk);

        // Banner format: "// Assembly: <name>  (<count> classes)\n" — the
        // two-space + "(" disambiguates Assembly-CSharp from the longer
        // Assembly-CSharp-firstpass.
        int firstpassIdx = text.IndexOf("// Assembly: Assembly-CSharp-firstpass  (", StringComparison.Ordinal);
        int mainIdx      = text.IndexOf("// Assembly: Assembly-CSharp  (",          StringComparison.Ordinal);

        Assert.True(firstpassIdx >= 0, "firstpass banner missing");
        Assert.True(mainIdx > firstpassIdx,
            "Assembly-CSharp banner should appear AFTER Assembly-CSharp-firstpass " +
            "(caller-supplied order), regardless of server row order.");
    }

    [Fact]
    public async Task ExportAsync_HandlesGetClassesError_WithErrorBannerNoCrash()
    {
        var asm = new[] { "BrokenAssembly" };
        var classes = new GetClassesResult
        {
            Assembly = "BrokenAssembly",
            Error    = "assembly not loaded",
        };

        (string text, Il2cppHeaderBatchExporter.BatchStats stats) =
            await Il2cppHeaderBatchExporter.ExportAsync(
                asm,
                getClasses:   (_, _) => Task.FromResult(classes),
                getClassInfo: (_, _, _, _) =>
                    Task.FromResult<GetClassInfoResult?>(null),
                ct: TestContext.Current.CancellationToken)
            .ConfigureAwait(true);

        Assert.Contains("// Assembly: BrokenAssembly", text);
        Assert.Contains("// ERROR: assembly not loaded", text);
        Assert.Equal(0, stats.ClassesEmitted);
    }
