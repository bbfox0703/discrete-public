// SdkHeaderExporter.cs — emits a C/C++ header describing the layout of a
// Unity managed class. Mirror of docs/Architecture.md §"SDK Header (.h)".
//
// Output is a single struct with field names, types (mapped via
// UnityTypeMap), and explicit `// +0x...` offset comments. Static / literal
// fields are skipped — they don't sit inside the instance.
//
// Inheritance: when GetClassInfoResult.Parent is set, parent fields are
// emitted first under a `/* inherited from ... */` banner, oldest-first.
// Caller is responsible for fetching the parent class info via
// BackendAdapter.GetClassInfoAsync and passing it as the optional ancestors
// list (oldest -> newest).

using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace UnityDumpUI.Core.Services.Export;

public static class SdkHeaderExporter
{
    /// <summary>
    /// Render an SDK header for <paramref name="self"/>. <paramref name="ancestors"/>
    /// is optional, ordered oldest-first (root → … → immediate parent); when
    /// supplied, those classes' instance fields are emitted before the
    /// declared ones with an inheritance banner.
    /// </summary>
    public static string Render(GetClassInfoResult self,
                                IReadOnlyList<GetClassInfoResult>? ancestors = null,
                                string? assemblyName = null)
    {
        var sb = new StringBuilder(2048);

        string ns   = self.Namespace ?? string.Empty;
        string nm   = self.Name      ?? "Unknown";
        string full = string.IsNullOrEmpty(ns) ? nm : $"{ns}.{nm}";
        string structName = SanitizeIdentifier(NestedToFlat(nm));

        sb.Append("// Generated by UnityCEDumper — SDK header\n");
        if (!string.IsNullOrEmpty(assemblyName))
            sb.Append("// Assembly: ").Append(assemblyName).Append('\n');
        sb.Append("// Class:    ").Append(full).Append('\n');
        if (self.Parent is { Name: { Length: > 0 } pn })
        {
            string pns = self.Parent.Namespace ?? string.Empty;
            sb.Append("// Parent:   ").Append(string.IsNullOrEmpty(pns) ? pn : $"{pns}.{pn}").Append('\n');
        }
        sb.Append("// Note:     offsets reflect the instance layout reported by the runtime.\n");
        sb.Append("//           Static / literal fields are omitted from the struct body.\n\n");

        sb.Append("#include <cstdint>\n\n");
        sb.Append("#pragma pack(push, 1)\n");
        sb.Append("struct ").Append(structName).Append(" {\n");

        if (ancestors is { Count: > 0 })
        {
            foreach (GetClassInfoResult anc in ancestors)
                EmitFieldsBlock(sb, anc, isInherited: true);
        }
        EmitFieldsBlock(sb, self, isInherited: false);

        sb.Append("};\n");
        sb.Append("#pragma pack(pop)\n");
        return sb.ToString();
    }

    private static void EmitFieldsBlock(StringBuilder sb, GetClassInfoResult info, bool isInherited)
    {
        if (info.Fields is not { Count: > 0 } fields) return;

        // Skip statics — they live in the type's static block, not instance memory.
        var instance = fields.Where(f => !f.Static).ToList();
        if (instance.Count == 0) return;

        if (isInherited)
        {
            string label = string.IsNullOrEmpty(info.Namespace)
                ? (info.Name ?? "?")
                : $"{info.Namespace}.{info.Name}";
            sb.Append("    /* inherited from ").Append(label).Append(" */\n");
        }

        foreach (FieldEntry f in instance)
        {
            ManagedTypeShape shape = UnityTypeMap.Resolve(f.Type);
            sb.Append("    ");
            sb.Append(shape.CHeaderType);
            sb.Append(' ');
            sb.Append(SanitizeIdentifier(f.Name));
            sb.Append(';');
            sb.Append("    // +0x");
            sb.Append(f.Offset.ToString("X", CultureInfo.InvariantCulture));
            if (!string.IsNullOrEmpty(f.Type))
                sb.Append("  ").Append(f.Type);
            sb.Append('\n');
        }
        if (isInherited) sb.Append('\n');
    }

    /// <summary>
    /// Replace characters that aren't valid in a C identifier with underscores;
    /// prefix a leading digit with `_`. Nested-type names like `Outer/Inner`
    /// become `Outer_Inner` — see <see cref="NestedToFlat"/>.
    /// </summary>
    internal static string SanitizeIdentifier(string raw)
    {
        if (string.IsNullOrEmpty(raw)) return "_";
        var sb = new StringBuilder(raw.Length);
        for (int i = 0; i < raw.Length; ++i)
        {
            char c = raw[i];
            bool ok = (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')
                   || (c >= '0' && c <= '9') || c == '_';
            sb.Append(ok ? c : '_');
        }
        if (sb[0] >= '0' && sb[0] <= '9') sb.Insert(0, '_');
        return sb.ToString();
    }

    /// <summary>Outer/Inner → Outer_Inner for use in C identifiers.</summary>
    internal static string NestedToFlat(string raw)
        => string.IsNullOrEmpty(raw) ? raw : raw.Replace('/', '_');
}
