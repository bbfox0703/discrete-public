// SymbolExporter.cs — render the IL2CPP symbol dump into label files that
// debuggers (x64dbg, Ghidra, IDA) can ingest. Mirrors the UE5CEDumper
// SymbolExportService surface but driven by Unity's
// dumpIl2cppSymbols RPC (class metadata pointers + AOT method entry
// points in GameAssembly.dll).
//
// Format briefs:
//
//  - **x64dbg `.dd64`** — JSON `{ labels: [...], comments: [...] }`. Each
//    label is `{ module, address, manual, text }`; address is module-
//    relative HEX *without* `0x` prefix (x64dbg refuses the prefix).
//
//  - **Ghidra** — text, one symbol per line: `LABEL ADDRESS TYPE`
//    (absolute hex with `0x`, type `f` for function / `l` for label).
//    Compatible with Ghidra's `ImportSymbolsScript.py`.
//
//  - **IDA `.idc`** — IDC script calling `MakeName(addr, name)` and
//    optional `MakeComm(addr, comment)`. Addresses are absolute hex.
//
// Label naming convention (single source of truth for all three formats):
//   class  rows → "Class_<Namespace>_<Class>"
//   method rows → "<Namespace>_<Class>__<Method>[_<HumanSuffix>]"
// All identifiers are sanitised to `[A-Za-z0-9_]`: spaces, generic
// punctuation (`<>` / `` ` `` / `.` / `/`) collapse to `_`. The
// `humanSuffix` is what keeps overloads from colliding ("noargs" /
// "int" / "3float" / "string_Card_Point", same shape as
// findMethodInstances — see dll/src/shared/MethodSignatureFormat.h).

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;

namespace UnityDumpUI.Core.Services.Export;

public static class SymbolExporter
{
    /// <summary>
    /// Render an x64dbg `.dd64` database (JSON). Addresses are
    /// module-relative hex without "0x" prefix — x64dbg parses raw hex
    /// against the named module, then resolves at load time. Set
    /// <paramref name="moduleName"/> to the file the debugger sees
    /// (typically "GameAssembly.dll").
    /// </summary>
    public static string RenderX64dbgDatabase(
        IReadOnlyList<SymbolDumpRow> rows,
        string                       moduleName,
        ulong                        moduleBase)
    {
        ArgumentNullException.ThrowIfNull(rows);
        if (string.IsNullOrEmpty(moduleName)) moduleName = "GameAssembly.dll";

        var labels   = new JsonArray();
        var comments = new JsonArray();

        foreach (var row in rows)
        {
            if (!TryParseHex(row.Address, out ulong absAddr)) continue;
            // x64dbg's .dd64 stores addresses as module-relative HEX without
            // "0x"; the debugger resolves them at load time. When moduleBase
            // is 0 (we couldn't locate the module) fall back to absolute —
            // the symbols still load, just without rebase support.
            ulong relAddr = moduleBase != 0 && absAddr >= moduleBase
                ? absAddr - moduleBase
                : absAddr;
            string relHex = relAddr.ToString("X", CultureInfo.InvariantCulture);

            string label = BuildLabel(row);
            labels.Add((JsonNode)new JsonObject
            {
                ["module"]  = moduleName,
                ["address"] = relHex,
                ["manual"]  = true,
                ["text"]    = label,
            });

            // Annotate non-class rows with the declaring class so a
            // disassembly user can see "AActor::Tick (3float)" in context
            // even though the label itself stays underscore-flat.
            if (row.Kind == "method")
            {
                string comment = BuildClassQualifier(row);
                if (!string.IsNullOrEmpty(comment))
                {
                    comments.Add((JsonNode)new JsonObject
                    {
                        ["module"]  = moduleName,
                        ["address"] = relHex,
                        ["manual"]  = true,
                        ["text"]    = comment,
                    });
                }
            }
        }

        var root = new JsonObject
        {
            ["labels"]   = labels,
            ["comments"] = comments,
        };
        return root.ToJsonString(new System.Text.Json.JsonSerializerOptions
        {
            WriteIndented = true,
        });
    }

    /// <summary>
    /// Render a Ghidra-importable symbol text file. One symbol per line in
    /// "LABEL ADDRESS TYPE" form — type is `f` for method rows (Ghidra
    /// treats these as function symbols) and `l` for class rows.
    /// Compatible with Ghidra's bundled `ImportSymbolsScript.py`.
    /// </summary>
    public static string RenderGhidraSymbols(IReadOnlyList<SymbolDumpRow> rows)
    {
        ArgumentNullException.ThrowIfNull(rows);
        var sb = new StringBuilder(rows.Count * 80);
        sb.AppendLine("// Generated by Discrete — Ghidra Symbol Import");
        sb.AppendLine("// Import via: ImportSymbolsScript.py");
        foreach (var row in rows)
        {
            if (string.IsNullOrEmpty(row.Address)) continue;
            string label = BuildLabel(row);
            string type  = row.Kind == "method" ? "f" : "l";
            sb.Append(label);
            sb.Append(' ');
            sb.Append(row.Address);   // absolute hex with 0x — Ghidra accepts that shape
            sb.Append(' ');
            sb.AppendLine(type);
        }
        return sb.ToString();
    }

    /// <summary>
    /// Render an IDA `.idc` script that names every symbol (and comments
    /// the method rows with their declaring class). Run via IDA's
    /// "File → Script file…" once the GameAssembly.dll image is loaded.
    /// </summary>
    public static string RenderIdaScript(IReadOnlyList<SymbolDumpRow> rows)
    {
        ArgumentNullException.ThrowIfNull(rows);
        var sb = new StringBuilder(rows.Count * 100);
        sb.AppendLine("#include <idc.idc>");
        sb.AppendLine();
        sb.AppendLine("// Generated by Discrete — IDA Symbol Import");
        sb.AppendLine("static main() {");
        foreach (var row in rows)
        {
            if (string.IsNullOrEmpty(row.Address)) continue;
            string addr  = row.Address;
            string label = BuildLabel(row);
            sb.Append("    MakeName(");
            sb.Append(addr);
            sb.Append(", \"");
            sb.Append(EscapeIdcString(label));
            sb.AppendLine("\");");

            if (row.Kind == "method")
            {
                string comment = BuildClassQualifier(row);
                if (!string.IsNullOrEmpty(comment))
                {
                    sb.Append("    MakeComm(");
                    sb.Append(addr);
                    sb.Append(", \"");
                    sb.Append(EscapeIdcString(comment));
                    sb.AppendLine("\");");
                }
            }
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    // ---- helpers ----------------------------------------------------------

    /// <summary>
    /// Build a debugger-safe label from a symbol row. Class rows produce
    /// "Class_<ns>_<name>"; method rows produce
    /// "<ns>_<class>__<method>[_<humanSuffix>]". All non-alnum/underscore
    /// characters collapse to '_'. Public for unit testing.
    /// </summary>
    public static string BuildLabel(SymbolDumpRow row)
    {
        ArgumentNullException.ThrowIfNull(row);
        var sb = new StringBuilder(64);
        if (row.Kind == "class")
        {
            sb.Append("Class_");
            AppendQualified(sb, row.Namespace, row.Class);
            return SanitizeLabel(sb.ToString());
        }
        // method
        AppendQualified(sb, row.Namespace, row.Class);
        sb.Append("__");
        sb.Append(string.IsNullOrEmpty(row.Name) ? "Anon" : row.Name);
        if (!string.IsNullOrEmpty(row.HumanSuffix))
        {
            sb.Append('_');
            sb.Append(row.HumanSuffix);
        }
        return SanitizeLabel(sb.ToString());
    }

    private static void AppendQualified(StringBuilder sb, string @namespace, string @class)
    {
        if (!string.IsNullOrEmpty(@namespace))
        {
            sb.Append(@namespace);
            sb.Append('_');
        }
        sb.Append(string.IsNullOrEmpty(@class) ? "Anon" : @class);
    }

    /// <summary>
    /// Format `<assembly>:<ns>.<class>` for use as a debugger comment.
    /// Returns empty string when there's nothing meaningful to qualify.
    /// </summary>
    private static string BuildClassQualifier(SymbolDumpRow row)
    {
        if (string.IsNullOrEmpty(row.Class)) return string.Empty;
        var sb = new StringBuilder(48);
        if (!string.IsNullOrEmpty(row.Assembly))
        {
            sb.Append(row.Assembly);
            sb.Append(':');
        }
        if (!string.IsNullOrEmpty(row.Namespace))
        {
            sb.Append(row.Namespace);
            sb.Append('.');
        }
        sb.Append(row.Class);
        return sb.ToString();
    }

    /// <summary>
    /// Collapse anything outside [A-Za-z0-9_] to '_'. Empty input → "unknown".
    /// Public so tests can pin the contract.
    /// </summary>
    public static string SanitizeLabel(string raw)
    {
        if (string.IsNullOrEmpty(raw)) return "unknown";
        var sb = new StringBuilder(raw.Length);
        foreach (char c in raw)
        {
            bool ok = (c >= '0' && c <= '9')
                   || (c >= 'A' && c <= 'Z')
                   || (c >= 'a' && c <= 'z')
                   || c == '_';
            sb.Append(ok ? c : '_');
        }
        return sb.Length == 0 ? "unknown" : sb.ToString();
    }

    private static string EscapeIdcString(string s)
    {
        // IDC string literals are C-style; escape backslash + double quote.
        return s.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

    private static bool TryParseHex(string? addr, out ulong value)
    {
        value = 0;
        if (string.IsNullOrEmpty(addr)) return false;
        ReadOnlySpan<char> span = addr;
        if (span.Length >= 2 && span[0] == '0' && (span[1] == 'x' || span[1] == 'X'))
        {
            span = span[2..];
        }
        return ulong.TryParse(span, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out value);
    }
}
