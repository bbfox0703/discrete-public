//! Regenerates the two Zydis-derived tables in dll/rust from the pinned Zydis
//! and checks them byte for byte against the repo files (never overwrites
//! them):
//!
//! * `dll/rust/src/chain/apx_map4.rs` — APX EVEX map 4 + EVEX-promoted VEX
//!   GPR decode facts for the chain detector (iced-x86 1.22 has no APX).
//! * `dll/rust/src/xref/apx_mem.rs` — the memory-operand access of the same
//!   encodings for the instance-field xref scan.
//!
//! Output goes to `$ORACLE_OUT_DIR` (build.ps1: `target/oracle-tables/`). On a
//! mismatch, diff that file against the repo one; copy it over only after
//! re-proving the decoder (README "Regenerating a table").
//!
//! The emitted header text is part of the byte-identical contract, so it is
//! reproduced verbatim; change it here and in the repo file together.

use std::collections::BTreeSet;
use std::path::PathBuf;

use crate::zydis::{chain_mnemonic_id, mnemonic_name, repo_path, split, zfacts, zy_chain};

/// EVEX-promoted encodings outside map 4 (VEX-only instructions in AVX-512
/// terms): (map, opcode). Shared by both tables and the apx_mem sweep.
pub(crate) const EXTRA_OPS: [(u8, u8); 28] = [
    (1, 0x90), (1, 0x91), (1, 0x92), (1, 0x93), (2, 0x49),
    (2, 0xE0), (2, 0xE1), (2, 0xE2), (2, 0xE3), (2, 0xE4), (2, 0xE5), (2, 0xE6), (2, 0xE7),
    (2, 0xE8), (2, 0xE9), (2, 0xEA), (2, 0xEB), (2, 0xEC), (2, 0xED), (2, 0xEE), (2, 0xEF),
    (2, 0xF2), (2, 0xF3), (2, 0xF5), (2, 0xF6), (2, 0xF7), (3, 0xF0), (7, 0xF8),
];

const GPR_NAMES: [&str; 16] =
    ["rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi", "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15"];

fn out_dir() -> PathBuf {
    let d = match std::env::var_os("ORACLE_OUT_DIR") {
        Some(d) => PathBuf::from(d),
        None => PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("target").join("oracle-tables"),
    };
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// Writes the generated text and asserts it equals the repo file.
fn write_and_compare(name: &str, repo_rel: &str, generated: &str) {
    let out = out_dir().join(name);
    std::fs::write(&out, generated).unwrap();
    let repo = repo_path(repo_rel);
    let want = std::fs::read(&repo).unwrap_or_else(|e| panic!("{}: {e}", repo.display()));
    if want == generated.as_bytes() {
        println!("[tables] {repo_rel}: regenerated byte-identical ({} bytes) -> {}", want.len(), out.display());
        return;
    }
    let w = String::from_utf8_lossy(&want);
    let line = w.lines().zip(generated.lines()).position(|(a, b)| a != b).map_or_else(
        || format!("all common lines equal; lengths {} vs {} bytes", want.len(), generated.len()),
        |i| format!("first difference at line {}", i + 1),
    );
    panic!("[tables] {repo_rel} differs from the regenerated {} ({line})", out.display());
}

// --- chain/apx_map4.rs -------------------------------------------------------

/// Map-4 / EXTRA table entry from Zydis (bit layout in the emitted header):
/// probes the encoding with vvvv = 0 and vvvv = 14, and with EVEX.R / R'
/// cleared, and reads validity, length and the written registers from the
/// chain projection. None = invalid in every probe.
#[allow(clippy::too_many_arguments)] // one argument per encoding field
fn mx_entry(mmm: u8, op: u8, mod3: bool, reg: u8, pp: u8, w: u8, nd: u8, nf: u8, names: &mut BTreeSet<String>) -> Option<u16> {
    let probe_p0 = |vv: u8, p0: u8| -> Option<(usize, String, String)> {
        let modrm = if mod3 { 0xC0 | (reg << 3) | 3 } else { 0x40 | (reg << 3) | 3 };
        let p1 = (w << 7) | ((!vv & 0xF) << 3) | 0x04 | pp;
        let p2 = (nd << 4) | 0x08 | (nf << 2);
        let b = [0x62, p0 | mmm, p1, p2, op, modrm, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88];
        let z = zy_chain(&b);
        if z == "X" {
            return None;
        }
        let len: usize = split(&z)[1..].split(' ').next().unwrap().parse().unwrap();
        let mn = mnemonic_name(chain_mnemonic_id(&z).unwrap());
        Some((len, split(&z).to_string(), mn))
    };
    let probe = |vv: u8| probe_p0(vv, 0xD0);
    let a = probe(0);
    let b = probe(14);
    let vv_ok = if b.is_some() { 14 } else { 0 };
    let r3_bad = (a.is_some() || b.is_some()) && probe_p0(vv_ok, 0x50).is_none();
    let r4_bad = (a.is_some() || b.is_some()) && probe_p0(vv_ok, 0xC0).is_none();
    let (used, (len, pj, mn)) = match (a, b) {
        (None, None) => return None,
        (Some(x), None) => (false, x),
        (_, Some(x)) => (true, x),
    };
    names.insert(mn.clone());
    let scc = mn.starts_with("ccmp") || mn.starts_with("ctest");
    let ml = if mod3 { 1 } else { 2 };
    let imm = len - 5 - ml;
    let immc = match imm {
        0 => 0u16,
        1 => 1,
        2 => 2,
        4 => 3,
        _ => panic!("imm {imm} {mn}"),
    };
    // The table can only express GPR writes: none of these encodings may be
    // a branch or carry a chain-relevant memory form.
    assert!(
        !pj.contains(" T")
            && !pj.contains(" B")
            && !pj.contains(" C")
            && !pj.contains("RD")
            && !pj.contains("WR")
            && !pj.contains("H2")
            && !pj.contains("MV"),
        "{mn} {pj}"
    );
    let mut v: u16 = u16::from(used) | (u16::from(scc) << 1) | (immc << 2) | (u16::from(r3_bad) << 12) | (u16::from(r4_bad) << 13);
    if let Some(wp) = pj.split(" W:").nth(1) {
        for n in wp.split(':') {
            if n == GPR_NAMES[reg as usize] {
                v |= 1 << 4;
            } else if n == "r11" && mod3 {
                v |= 1 << 5;
            } else if n == "r14" && used {
                v |= 1 << 6;
            } else if let Some(i) = GPR_NAMES.iter().position(|x| *x == n) {
                assert!(v >> 7 == 0, "two literals {mn} {pj}");
                v |= ((i as u16) + 1) << 7;
            } else {
                names.insert(format!("nongpr-write:{n}"));
            }
        }
    }
    Some(v)
}

fn emit_apx_map4() -> String {
    let mut names = BTreeSet::new();
    let mut profiles: Vec<Vec<u16>> = vec![vec![0; 32]];
    let intern = |prof: Vec<u16>, profiles: &mut Vec<Vec<u16>>| match profiles.iter().position(|p| *p == prof) {
        Some(i) => i,
        None => {
            profiles.push(prof);
            profiles.len() - 1
        }
    };
    let row = |mmm: u8, op: u8, mod3: bool, reg: u8, names: &mut BTreeSet<String>| {
        let mut prof = vec![];
        for pp in 0..4u8 {
            for w in 0..2u8 {
                for nd in 0..2u8 {
                    for nf in 0..2u8 {
                        prof.push(mx_entry(mmm, op, mod3, reg, pp, w, nd, nf, names).map_or(0, |v| v | 0x8000));
                    }
                }
            }
        }
        prof
    };
    let mut groups = vec![];
    for op in 0..=255u8 {
        for mod3 in [false, true] {
            for reg in 0..8u8 {
                let prof = row(4, op, mod3, reg, &mut names);
                groups.push(intern(prof, &mut profiles));
            }
        }
    }
    let mut extra = vec![];
    for &(mmm, op) in &EXTRA_OPS {
        let mut idxs = vec![];
        for mod3 in [false, true] {
            for reg in 0..8u8 {
                let prof = row(mmm, op, mod3, reg, &mut names);
                idxs.push(intern(prof, &mut profiles));
            }
        }
        extra.push((mmm, op, idxs));
    }
    let mut s = String::new();
    s += "//! APX EVEX decode facts (map 4 \"promoted legacy\" instructions and the\n";
    s += "//! EVEX-promoted VEX GPR instructions), GENERATED from Zydis 5.0 (commit\n";
    s += "//! 17bc6fb, the legacy DLL's pin) by tools/zydis-oracle\n";
    s += "//! (`build.ps1 -Mode tables`). iced-x86 1.22 has no APX support, so the chain\n";
    s += "//! detector answers these encodings from this table instead.\n";
    s += "//!\n";
    s += "//! `GROUP[op << 4 | mod3 << 3 | modrm.reg]` (map 4) or an `EXTRA` row\n";
    s += "//! (`[mod3 << 3 | modrm.reg]`) selects a row of `PROFILES`; the row is\n";
    s += "//! indexed by `pp << 3 | W << 2 | ND << 1 | NF`. Entry bits: 15 valid,\n";
    s += "//! 0 vvvv encodes an operand (else it must be 0 with V' = 1), 1 SCC form\n";
    s += "//! (ccmp/ctest: vvvv, V' and aaa are condition data), 2-3 immediate size\n";
    s += "//! code (0, 1, 2, 4 bytes), 4 writes ModRM.reg, 5 writes ModRM.rm\n";
    s += "//! (register form), 6 writes vvvv, 7-11 fixed GPR written + 1, 12 EVEX.R\n";
    s += "//! must be 0 (ModRM.reg is a mask register), 13 EVEX.R' must be 0.\n\n";
    s += &format!("#[rustfmt::skip]\npub(super) static PROFILES: [[u16; 32]; {}] = [\n", profiles.len());
    for p in &profiles {
        s += "    [";
        s += &p.iter().map(|v| format!("0x{v:04X}")).collect::<Vec<_>>().join(", ");
        s += "],\n";
    }
    s += "];\n\n";
    s += "#[rustfmt::skip]\npub(super) static GROUP: [u8; 4096] = [\n";
    for chunk in groups.chunks(32) {
        s += "    ";
        s += &chunk.iter().map(|v| format!("{v}")).collect::<Vec<_>>().join(", ");
        s += ",\n";
    }
    s += "];\n\n";
    s += "/// EVEX-promoted encodings outside map 4 (VEX-only instructions in AVX-512\n";
    s += "/// terms, so iced rejects every EVEX form): (map, opcode, row per\n";
    s += "/// `mod3 << 3 | modrm.reg`).\n";
    s += &format!("#[rustfmt::skip]\npub(super) static EXTRA: [(u8, u8, [u8; 16]); {}] = [\n", extra.len());
    for (m, o, i) in &extra {
        s += &format!("    ({m}, 0x{o:02X}, [{}]),\n", i.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(", "));
    }
    s += "];\n";
    s
}

#[test]
fn apx_map4_regenerates() {
    write_and_compare("apx_map4.rs", "dll/rust/src/chain/apx_map4.rs", &emit_apx_map4());
}

// --- xref/apx_mem.rs ---------------------------------------------------------

/// Zydis action of the (single, visible) memory operand of an APX EVEX
/// memory form: 0 = none / invalid, 1 = read, 2 = write. Asserts the answer
/// does not depend on vvvv, base / SIB or displacement form (the invariance
/// the table relies on).
fn apx_act(mmm: u8, op: u8, reg: u8, sel: u8) -> u8 {
    let pp = sel >> 3;
    let w = (sel >> 2) & 1;
    let nd = (sel >> 1) & 1;
    let nf = sel & 1;
    let mut res: Option<u8> = None;
    for vv in [0u8, 6, 14] {
        for (modrm_lo, tail) in [(0x43u8, [0x11u8, 0, 0, 0]), (0x80 | 6, [0x44, 0x33, 0x22, 0x91]), (0x44, [0x20, 0xF0, 0, 0])] {
            let modrm = modrm_lo | (reg << 3);
            let p1 = (w << 7) | ((!vv & 0xF) << 3) | 0x04 | pp;
            let p2 = (nd << 4) | 0x08 | (nf << 2);
            let p0 = if mmm == 4 { 0xF4 } else { 0xD0 | mmm };
            let mut b = vec![0x62, p0, p1, p2, op, modrm];
            b.extend_from_slice(&tail);
            b.extend_from_slice(&[0x55, 0x66, 0x77, 0x88, 0x99]);
            let f = zfacts(&b);
            if f.n < 0 {
                continue;
            }
            assert_eq!(f.n, 1, "{b:02X?}");
            let a = f.acts[0];
            let v = if a & 0x0A != 0 {
                2
            } else if a & 0x05 != 0 {
                1
            } else {
                0
            };
            if let Some(prev) = res {
                assert_eq!(prev, v, "{b:02X?}");
            }
            res = Some(v);
        }
    }
    res.unwrap_or(0)
}

fn emit_apx_mem() -> String {
    let mut rows: Vec<u64> = vec![0];
    let idx = |row: u64, rows: &mut Vec<u64>| -> usize {
        match rows.iter().position(|r| *r == row) {
            Some(i) => i,
            None => {
                rows.push(row);
                rows.len() - 1
            }
        }
    };
    let row_of = |mmm: u8, op: u8, reg: u8| -> u64 {
        let mut row = 0u64;
        for sel in 0..32u8 {
            row |= u64::from(apx_act(mmm, op, reg, sel)) << (2 * sel);
        }
        row
    };
    let mut map4 = vec![];
    for op in 0..=255u8 {
        for reg in 0..8u8 {
            let r = row_of(4, op, reg);
            map4.push(idx(r, &mut rows));
        }
    }
    let mut extra = vec![];
    for &(mmm, op) in &EXTRA_OPS {
        let mut v = vec![];
        for reg in 0..8u8 {
            let r = row_of(mmm, op, reg);
            v.push(idx(r, &mut rows));
        }
        extra.push((mmm, op, v));
    }
    let mut s = String::new();
    s += "//! Memory-operand access of the APX EVEX encodings the chain detector\n";
    s += "//! answers from `chain::apx_map4` (map 4 \"promoted legacy\" instructions and\n";
    s += "//! the EVEX-promoted VEX GPR instructions) — iced-x86 1.22 cannot decode\n";
    s += "//! them, so the instance-field scan needs Zydis' answer from a table too.\n";
    s += "//! GENERATED from Zydis 5.0 (commit 17bc6fb, the legacy DLL's pin; decoder\n";
    s += "//! LONG_64, default modes) by tools/zydis-oracle\n";
    s += "//! (`build.ps1 -Mode tables`); do not edit by hand.\n";
    s += "//!\n";
    s += "//! Every such memory form has exactly one memory operand, always visible,\n";
    s += "//! with an unscaled displacement (disp8 * 1). Its access depends only on\n";
    s += "//! (map, opcode, ModRM.reg, pp, W, ND, NF) — measured invariant under vvvv,\n";
    s += "//! base / SIB / displacement form. `MAP4[op << 3 | reg]` (map 4) or an\n";
    s += "//! `EXTRA` entry selects a `ROWS` word holding 2 bits per\n";
    s += "//! `pp << 3 | W << 2 | ND << 1 | NF`: 1 = read (ACTION_MASK_READ only),\n";
    s += "//! 2 = write (ACTION_MASK_WRITE set), 0 = no such memory form.\n\n";
    s += "use crate::chain::decode::MemAct;\n\n";
    s += &format!("#[rustfmt::skip]\nstatic ROWS: [u64; {}] = [\n", rows.len());
    for r in &rows {
        s += &format!("    0x{r:016X},\n");
    }
    s += "];\n\n";
    s += "#[rustfmt::skip]\nstatic MAP4: [u8; 2048] = [\n";
    for c in map4.chunks(32) {
        s += "    ";
        s += &c.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(", ");
        s += ",\n";
    }
    s += "];\n\n";
    s += &format!("#[rustfmt::skip]\nstatic EXTRA: [(u8, u8, [u8; 8]); {}] = [\n", extra.len());
    for (m, o, v) in &extra {
        s += &format!("    ({m}, 0x{o:02X}, [{}]),\n", v.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "));
    }
    s += "];\n\n";
    s += "/// Access of the memory operand of the APX EVEX memory form `(mmm, op,\n";
    s += "/// reg)` with `sel = pp << 3 | W << 2 | ND << 1 | NF`.\n";
    s += "pub(crate) fn mem_act(mmm: u8, op: u8, reg: u8, sel: u8) -> MemAct {\n";
    s += "    let row = if mmm == 4 {\n";
    s += "        MAP4[(usize::from(op) << 3) | usize::from(reg & 7)]\n";
    s += "    } else {\n";
    s += "        match EXTRA.iter().find(|(m, o, _)| *m == mmm && *o == op) {\n";
    s += "            Some((_, _, r)) => r[usize::from(reg & 7)],\n";
    s += "            None => 0,\n";
    s += "        }\n";
    s += "    };\n";
    s += "    match (ROWS[usize::from(row)] >> (2 * u32::from(sel & 31))) & 3 {\n";
    s += "        1 => MemAct::Read,\n";
    s += "        2 => MemAct::Write,\n";
    s += "        _ => MemAct::None,\n";
    s += "    }\n";
    s += "}\n";
    s
}

